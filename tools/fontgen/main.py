def glyph_bytes(art: str) -> list:
    rows = art.split()
    assert len(rows) == 8, art
    out = []
    for row in rows:
        assert len(row) == 8, (row, art)
        b = 0
        for i, ch in enumerate(row):
            if ch == '#':
                b |= 0x80 >> i
        out.append(b)
    return out


def main() -> None:
    lines = []
    lines.append('package render')
    lines.append('')
    lines.append('// Code generated by tools/fontgen/main.py. DO NOT EDIT.')
    lines.append('')
    lines.append('// fontGlyphs holds the 8x8 bitmap font of the game.')
    lines.append('//')
    lines.append('// The table is indexed by (rune - firstRune); each entry holds the')
    lines.append('// eight rows of the glyph, most significant bit on the left.')
    lines.append('// A set bit means an opaque pixel.')
    lines.append('var fontGlyphs = [][8]byte{')
    for code in range(32, 127):
        ch = chr(code)
        art = GLYPHS[ch]
        data = glyph_bytes(art)
        hexs = ', '.join('0x%02x' % b for b in data)
        lines.append('\t{%s}, // %d %r' % (hexs, code, ch))
    lines.append('}')
    lines.append('')
    lines.append('// firstRune is the first rune of the font table.')
    lines.append('const firstRune = 32')
    lines.append('')
    lines.append('// lastRune is the last rune of the font table.')
    lines.append('const lastRune = 126')
    lines.append('')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
